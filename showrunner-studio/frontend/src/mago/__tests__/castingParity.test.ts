const { casting } = fixtures;

/** The model call, answered from a case's canned responses and validated the
 *  way _call_gemini validates Gemini's. */
const cannedCall = (responses: unknown[], sent: string[][]): StructuredCall => {
  const queue = [...responses];
  return async ({ contents, model, stepLabel }) => {
    sent.push(contents);
    const suffix = stepLabel ? ` (${stepLabel})` : "";
    try {
      return coerceModel(model, queue.shift());
    } catch (error) {
      if (error instanceof CastingValidationError)
        throw new CastingCallError(
          `Invalid response from model${suffix}`,
          error.message
        );
      throw error;
    }
  };
};

describe("casting matches the backend", () => {
  it.each(casting.parseSequences)("parseSequences", ({ input, output }) => {
    expect(parseSequences(input)).toEqual(output);
  });

  it.each(casting.extractSupplementaryText)(
    "extractSupplementaryText",
    ({ input, output }) => {
      expect(extractSupplementaryText(input, parseSequences(input))).toBe(
        output
      );
    }
  );

  it.each(casting.resolveShotDuration)(
    "resolveShotDuration(%j)",
    ({ input, output }) => {
      expect(resolveShotDuration(...input)).toEqual(output);
    }
  );

  it.each(casting.cases)("generateCasting $name", async (testCase) => {
    const sent: string[][] = [];
    const options = testCase.options;
    const run = generateCasting(
      testCase.script,
      cannedCall(testCase.responses, sent),
      {
        shotLimit: (options.shot_limit as number | undefined) ?? null,
        atomicShots: !!options.atomic_shots,
        includeDialogue: !!options.include_dialogue,
        sequenceMode: !!options.sequence_mode,
        singleCallMaxWords: options.single_call_max_words as number | undefined
      }
    );
    if (testCase.error) {
      await expect(run).rejects.toThrow(testCase.error);
    } else {
      const local = await run;
      if (local.shots_error)
        local.shots_error = {
          message: (local.shots_error as { message: string }).message
        };
      expect(local).toEqual(testCase.casting);
    }
    expect(sent).toEqual(testCase.calls.map((call) => call.contents));
  });
});
